import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// This generator documents example `.collection('x')` / `.doc('x/...')` calls in
// its own comments; skip its own source so those examples don't pollute the list.
const SELF_PATH = fileURLToPath(import.meta.url);

/**
 * Q5 (DOC-02) — Firestore collection inventory generator.
 *
 * Scans the runtime source (lib/, app/, scripts/) for statically-written Firestore
 * collection references and emits a deterministic, committed inventory at
 * docs/database/collections.generated.md. CI regenerates it and `git diff
 * --exit-code`s the result, so adding or removing a collection without
 * regenerating fails the build (same drift-gate pattern as the OpenAPI spec).
 *
 * This is an INVENTORY (which collections exist), not a field-level schema — the
 * curated field notes live in docs/database/schema.md. Only string-literal
 * references are captured; dynamically-named collections (e.g. `db.collection(name)`)
 * cannot be resolved statically and are intentionally out of scope.
 */

const ROOTS = ['lib', 'app', 'scripts'];
const SOURCE_EXT = /\.(ts|tsx|mjs|js)$/;
const OUTPUT_PATH = path.resolve('docs/database/collections.generated.md');

// A valid Firestore collection id we are willing to document: starts with a
// letter, then letters/digits/underscores. Filters out template-literal noise.
const NAME_RE = /^[a-zA-Z][a-zA-Z0-9_]*$/;

// `.collection('x')` and `.collectionGroup('x')`
const COLLECTION_RE = /\.collection(?:Group)?\(\s*['"]([^'"]+)['"]/g;
// `.doc('x/...')` — the first path segment is a collection id.
const DOC_RE = /\.doc\(\s*['"]([^'"$]+)['"]/g;

/**
 * Recursively collects source files under a directory.
 * @param {string} directory
 * @param {string[]} out
 */
async function collectSourceFiles(directory, out) {
  let entries;
  try {
    entries = await fs.readdir(directory, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      await collectSourceFiles(full, out);
      continue;
    }
    if (entry.isFile() && SOURCE_EXT.test(entry.name) && path.resolve(full) !== SELF_PATH) {
      out.push(full);
    }
  }
  return out;
}

/**
 * Extracts distinct, valid collection ids from source text.
 * @param {string} content
 * @param {Set<string>} into
 */
function extractCollections(content, into) {
  let match;
  while ((match = COLLECTION_RE.exec(content))) {
    if (NAME_RE.test(match[1])) into.add(match[1]);
  }
  while ((match = DOC_RE.exec(content))) {
    const segment = match[1].split('/')[0];
    if (NAME_RE.test(segment)) into.add(segment);
  }
}

/**
 * Builds deterministic markdown for the inventory.
 * @param {string[]} collections sorted collection ids
 * @returns {string}
 */
function createMarkdown(collections) {
  const lines = [
    '# Firestore Collection Inventory (generated)',
    '',
    '> Generated by `scripts/generate-firestore-schema.mjs` (`npm run docs:schema`).',
    '> Do not edit by hand — CI regenerates this file and fails on drift (DOC-02).',
    '',
    'This is a data **inventory** — the complete set of Firestore collections that the',
    'application code writes to or reads from. Field-level notes for the core',
    'collections live in [`schema.md`](./schema.md).',
    '',
    'Notes:',
    '',
    '- Tenant data lives in **top-level collections filtered by `tenantId`** (not',
    '  subcollections); isolation is enforced at the API-route level because the Admin',
    '  SDK bypasses Firestore rules.',
    '- Only string-literal references are captured. Dynamically-named collections',
    '  (e.g. `db.collection(variable)`) cannot be resolved statically and are not listed.',
    '- Naming is intentionally reported as-written; duplicates that differ only by case',
    '  or delimiter (e.g. `audit_logs` vs `auditLogs`) reflect real naming drift to',
    '  reconcile, not generator noise.',
    '',
    `## Collections (${collections.length})`,
    '',
    ...collections.map((name) => `- \`${name}\``),
  ];
  return `${lines.join('\n')}\n`;
}

async function main() {
  const files = [];
  for (const root of ROOTS) {
    await collectSourceFiles(path.resolve(root), files);
  }

  const collections = new Set();
  for (const file of files) {
    const content = await fs.readFile(file, 'utf8');
    extractCollections(content, collections);
  }

  const sorted = [...collections].sort((a, b) => a.localeCompare(b));
  const markdown = createMarkdown(sorted);
  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, markdown, 'utf8');

  process.stdout.write(
    `Generated Firestore inventory with ${sorted.length} collections at ${OUTPUT_PATH}\n`,
  );
}

main().catch((error) => {
  process.stderr.write(`${error.stack || error.message}\n`);
  process.exit(1);
});
